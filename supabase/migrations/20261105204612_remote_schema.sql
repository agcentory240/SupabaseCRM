CREATE OR REPLACE FUNCTION public.change_task_status (
  p_task_id    bigint,
  p_new_status text,
  p_comment    text   DEFAULT NULL::text
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_current_status text;
  v_assignee uuid;
  v_is_manager boolean;
  v_allowed boolean := false;
begin
  -- 1. Проверяем, что пользователь — менеджер
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'manager'
  ) into v_is_manager;

  -- 2. Получаем текущий статус и исполнителя задачи
  select status, assignee_id into v_current_status, v_assignee
  from public.tasks
  where id = p_task_id;

  if not found then
    raise exception 'Task not found';
  end if;

  -- 3. Проверяем допустимость перехода
  if v_current_status = 'new' and p_new_status = 'in_progress'
     and v_assignee = (select auth.uid()) then
    v_allowed := true;

  elsif v_current_status = 'in_progress' and p_new_status = 'on_review'
     and v_assignee = (select auth.uid()) then
    v_allowed := true;

  elsif v_current_status = 'on_review' and p_new_status = 'accepted'
     and v_is_manager then
    v_allowed := true;

  elsif v_current_status = 'on_review' and p_new_status = 'needs_rework'
     and v_is_manager and p_comment is not null then
    v_allowed := true;

  elsif v_current_status = 'needs_rework' and p_new_status = 'in_progress'
     and v_assignee = (select auth.uid()) then
    v_allowed := true;
  end if;

  if not v_allowed then
    raise exception 'Transition from % to % is not allowed for this user',
      v_current_status, p_new_status;
  end if;

  -- 4. Обновляем статус
  update public.tasks
  set status = p_new_status
  where id = p_task_id;

  -- 5. Пишем историю
  insert into public.task_history (
    task_id, from_status, to_status, comment, changed_by
  ) values (
    p_task_id, v_current_status, p_new_status, p_comment, (select auth.uid())
  );
end;
$function$;

REVOKE ALL ON FUNCTION "public"."change_task_status"(bigint, text, text) FROM PUBLIC, "anon", "service_role";

CREATE OR REPLACE FUNCTION public.handle_new_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$begin
  insert into public.profiles (id, email, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'role', 'worker')
  );
  return new;
end;$function$;

REVOKE ALL ON FUNCTION "public"."handle_new_user"() FROM "anon", "authenticated", "service_role";

